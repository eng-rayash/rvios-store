// إنهاء نظيف للاختبارات على ويندوز.
//
// المشكلة: استدعاء process.exit() بينما مقابس fetch المُبقاة حيّة
// (keep-alive) ما تزال مفتوحة يُسقط libuv بـ:
//   Assertion failed: !(handle->flags & UV_HANDLE_CLOSING), src\win\async.c
// فتنجح كل الفحوص ثم يعود الأمر برمز خروج فاشل — وهو أسوأ من الفشل
// الصريح لأنه يوهم بخلل غير موجود.
//
// الحل: لا نقتل العملية ولا نلمس موزّع undici (استدعاء destroy عليه
// يرمي TypeError من داخله). نضبط exitCode فقط وندع Node يخرج وحده
// حين تُغلق المقابس بمهلة keep-alive الافتراضية.
//
// ملاحظة: هذه المجموعات تفترض قاعدة بيانات طازجة — تؤكّد أعداداً
// محددة (٩ منتجات، ٣ متاجر)، كما أن حدّ المعدل على طلب رمز التحقق
// (٣ محاولات لكل ١٠ دقائق) يرفض التشغيل المتكرر. لذلك يبدأ
// `npm test` بـ `npm run reset`.
export function finish(fail) {
  process.exitCode = fail ? 1 : 0;
}
