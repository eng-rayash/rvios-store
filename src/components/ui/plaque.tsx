import type { ComponentPropsWithoutRef, ElementType, ReactNode } from 'react';
import { cn } from '@/lib/utils';

/**
 * اللوح المعلّق — العنصر التوقيعي للعلامة (§٧٫٣).
 *
 * الوثيقة تصف المفهوم البصري المحوري: «لوحة محل معلّقة واضحة في
 * المقدمة، بينما لوحات محلات أخرى تتلاشى في الخلفية». وكان
 * منفَّذاً في موضعين: صفحة ٤٠٤ وعمود صفحة التسجيل. موضعان لا
 * يصنعان لغةً بصرية.
 *
 * ★ لماذا مكوّن لا صنف CSS وحده؟
 * لأن القرار المتكرّر ليس «أي أصناف» بل **أي وسم**. بطاقةُ طلبٍ
 * هي `article`، وعنصرُ قائمةٍ هو `li`، ولوحُ قسمٍ قد يكون
 * `section`. تركُ ذلك للاستدعاء يعني أن نصفها سيصير `div` —
 * وهو بالضبط ما يكسر البند الدلالي في قائمة الجودة. فالوسم هنا
 * وسيطٌ مطلوب التفكير فيه، لا افتراضٌ صامت.
 *
 * والأصناف في `globals.css` لا هنا: الخامة كلها (`.grain`,
 * `.hairline`, `.sheen`, `.lume`) تعيش هناك، ولوحٌ يُعرَّف في
 * TSX بينما توائمه في CSS يضيع بين الملفّين.
 */
export function Plaque({
  as: Tag = 'div' as ElementType,
  rail = false,
  ink = false,
  crest = false,
  lift = false,
  className,
  children,
  ...rest
}: {
  /** الوسم الدلالي — `article` لبطاقة قائمة بذاتها، `li` داخل قائمة */
  as?: ElementType;
  /**
   * القضيب النحاسي والسلكان فوق اللوح.
   *
   * ★ يحتاج متّسعاً فوقه (`pt-4` فأكثر على الحاوية) — القضيب
   * يطفو خارج حدود اللوح بأربعة عشر بكسلاً، فبلا متّسع يصطدم
   * بما قبله. ولهذا هو اختيارٌ لا افتراض: لحظات البطولة تستحقّه،
   * وشبكةٌ من اثنتي عشرة بطاقة لا تستحقّه — وثلاثون قضيباً على
   * شاشة واحدة تُقرأ زينةً لا توقيعاً.
   */
  rail?: boolean;
  /** اللوح على أرضية داكنة: يُضيء بدل أن يُظلم، وحدّه نحاسي */
  ink?: boolean;
  /**
   * تاجٌ علوي بلون المتجر — يحوّل «لوحاً» إلى «لوحة *هذا* المحل».
   * يُستعمل حيث يمثّل اللوح متجراً بعينه، لا حيث هو مجرّد سطح.
   */
  crest?: boolean;
  /** يرتفع عند التحويم — وهو ما تَعِد به باقة «بلس» حرفياً */
  lift?: boolean;
  className?: string;
  children: ReactNode;
  /* بقية الخصائص من `div`: `id` و`role` و`aria-*` و`onClick`.
     تكفي كل استعمالات اللوح، ولا تفتح الباب لأي خاصية. */
} & Omit<ComponentPropsWithoutRef<'div'>, 'className' | 'children'>
  /* `type` و`disabled` حين يُركَّب اللوح زرّاً (`as="button"`). وبلا
     `type` صريح يصير الزرّ داخل أي نموذجٍ زرَّ إرسالٍ افتراضياً. */
  & Pick<ComponentPropsWithoutRef<'button'>, 'type' | 'disabled'>) {
  return (
    <Tag
      className={cn(
        'plaque',
        ink && 'plaque-ink',
        crest && 'plaque-crest',
        rail && 'plaque-rail',
        lift && 'plaque-lift',
        className,
      )}
      {...rest}
    >
      {children}
    </Tag>
  );
}
