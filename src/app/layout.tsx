/**
 * ═══════════ خطوط الهوية ═══════════
 *
 * خطّان خاصّان يحملان الشخصية في العناوين، وخطّ نصّ **متغيّر**
 * يحمل التسلسل الطباعي في الجسم، وخطّ احتياطي واحد للتغطية.
 *
 * ★ لماذا تغيّر خطّ النصّ:
 * كان «شهد» — ملفٌّ **بوزن واحد ثقيل** يُعلَن `'100 900'` كي
 * يمتنع المتصفح عن التغليظ الصناعي. والقرار كان صحيحاً في
 * غايته وكارثياً في أثره: حين يخدم وجهٌ واحد كل الأوزان يصير
 * `font-bold` و`font-normal` **الشيء نفسه**. أي أن الجسم كان
 * بلا تسلسل طباعي إطلاقاً — كل تمييز محمول على الحجم واللون.
 *
 * و«ريدكس برو» متغيّر فعلاً (محور wght من ١٦٠ إلى ٧٠٠ في ملف
 * واحد): وزنٌ حقيقي لكل درجة، بلا تشويه، وبطلب شبكة واحد.
 * ومنخفض التباين دافئ الحدود — يخدم اتجاه «تحريري/بوتيك»
 * المعلن في §٧٫٢ بدل البرودة الهندسية التي نُميّز أنفسنا عنها.
 *
 * وثغرات المحارف تبقى قائمة في الخطّين الخاصّين:
 *   · «مغفرة» لا يحوي « » ولا — ولا … وهي في عناويننا.
 *   · «يباري» لاتيني خالص بلا عربية ولا أرقام عربية-هندية.
 * فيلتقطها «مركزي» خلفهما — خطٌّ من العائلة نفسها لا خطّ نظام
 * عشوائي، وإلا قُرئ العنوان الواحد بوجهين.
 *
 * وكلها تُستضاف ذاتياً عبر next/font: لا رحلة إلى fonts.googleapis
 * عند كل زيارة، ولا وميض نصّ بلا خطّ على شبكة يمنية بطيئة.
 */
/**
 * ★ «مركزي» صار خطّ النصّ — فيُحمَّل مسبقاً.
 *
 * كان `preload: false` صحيحاً حين كان طبقة تغطية لا يطلبها إلا
 * حرفٌ لاتيني هنا وشرطةٌ هناك. أمّا الآن فكل حرف في الواجهة
 * يمرّ عليه، وتأخيره يعني صفحةً كاملة تنتظر — أو تُرسم بخطّ
 * النظام ثم تقفز. فالتحميل المسبق هنا هو الصواب بعد أن انقلب
 * دوره، والقرار نفسه ينقلب معه.
 */
/**
 * ★★ فخٌّ كلّفنا الموقع كلّه — لا تُعِده:
 * **مصفوفة أوزان على خطّ Google متغيّر تُسقط الوجه بصمت.**
 *
 * الوثيقة صريحة: المصفوفة «إن لم يكن الخطّ متغيّراً». و«مركزي»
 * متغيّر، فكانت `weight: ['400','500','600','700']` هنا تعني أن
 * Next لا يُصدر له `@font-face` حقيقياً أصلاً — بل وجهَ بديلٍ
 * يُعيد تعيين Times New Roman. ولم يظهر ذلك سنةً لأن خطّ الجسم
 * كان ملفاً محلياً حقيقياً، فلم يكن أحد يرى غياب طبقة التغطية.
 *
 * ولا شيء يكسر: لا خطأ بناء، ولا تحذير في السجلّ، ولا فرق يُرى
 * إلا لمن يقرأ `@font-face` في CSS المُخدَّم. وهذا أخطر أنواع
 * العطب — الذي يعمل الموقع معه ويبدو أرخص فحسب.
 */
const markazi = Markazi_Text({
  subsets: ['arabic', 'latin'],
  variable: '--font-markazi',
  display: 'swap',
});

/**
 * ★ `weight: '100 900'` على ملفٍ بوزن واحد ليست خطأً بل قصد:
 * تُخبر المتصفح أن هذا الوجه يخدم كل الأوزان، فيمتنع عن
 * **تغليظ صناعي** (faux bold) يشوّه المحرف العربي المزخرف —
 * يُسمّك حروفه ويُغلق عيون الحلقات. البدائل أسوأ: إمّا وزن
 * واحد مُعلَن فيُغلَّظ صناعياً عند كل `font-bold`، أو أوزان
 * نطلبها ولا وجود لملفاتها.
 */
const maghfira = localFont({
  src: '../../public/fonts/rtl-maghfira-ramadan.ttf',
  variable: '--font-maghfira',
  weight: '100 900',
  display: 'swap',
  adjustFontFallback: false,        // مقاييس Arial لا تصف وجهاً عربياً مزخرفاً
  fallback: ['Markazi Text', 'Georgia', 'serif'],
});

const yapari = localFont({
  src: '../../public/fonts/YapariTrial-Bold.ttf',
  variable: '--font-yapari',
  weight: '100 900',
  display: 'swap',
  fallback: ['Markazi Text', 'Georgia', 'serif'],
});

