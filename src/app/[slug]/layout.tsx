import type { ReactNode } from 'react';

/**
 * تخطيط صفحات المتاجر — لعامل الخدمة وحده.
 *
 * ★ ثالث موضع تسقط فيه العلّة نفسها.
 * `store.html` القديمة كانت تحمّل `pwa.js`، وترحيل واجهة المتجر
 * إلى Next أسقطه بصمت كما أسقطه ترحيل الدخول واللوحة من قبل —
 * فصارت `<link rel="manifest">` معلَنةً في كل صفحة بلا عاملٍ
 * يُسجَّل خلفها. الوسم بلا العامل واجهةٌ بلا محرّك.
 *
 * والخسارة هنا أثقل من اللوحة: زائر المتجر عميلٌ على شبكة جوّال
 * بطيئة، وهو الذي كُتب عامل الخدمة لأجله أصلاً — «سرعة الزيارة
 * الثانية» في رأس `public/sw.js`. التاجر يفتح لوحته على شبكة
 * أفضل وأقلّ تكراراً.
 *
 * ★ `<script defer>` لا `next/script` — للسبب المشروح في
 * `(auth)/layout.tsx`: التسجيل داخل مستمع `load`، و
 * `afterInteractive` قد يُحقن بعد انطلاقه على صفحةٍ سريعة فلا
 * يُسجَّل شيء ولا يظهر خطأ.
 *
 * ولا nonce هنا: هذه المسارات خارج مطابقة `src/proxy.ts` عمداً
 * (سياسة nonce تُجبر التصيير عند الطلب، وصفحة المتجر تُصيَّر
 * ساكنةً لأجل السرعة)، فترويساتها من `SECURITY_HEADERS` بلا CSP.
 */
export default function StoreLayout({ children }: { children: ReactNode }) {
  return (
    <>
      {children}
      <script src="/assets/js/pwa.js" defer />
    </>
  );
}
