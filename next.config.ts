import type { NextConfig } from 'next';

/**
 * إعداد الترحيل التدريجي (strangler-fig).
 *
 * التطبيق الجديد يعمل بجوار الخادم القديم لا بدلاً منه: ما لم
 * يُرحَّل بعد يُمرَّر إليه كما هو، فيبقى الموقع كاملاً وقابلاً
 * للإطلاق في كل لحظة من الترحيل بدل أن يتوقّف أسابيع.
 *
 * ثلاثة مسارات تُمرَّر:
 *   /api      — المصادقة والطلبات والفوترة، لم تُرحَّل بعد
 *   /assets   — الصور والخطوط المشتركة بين النظامين
 *   /uploads  — صور التجّار (قرص محلي أو R2 حسب الإعداد)
 *
 * وبعد اكتمال الترحيل يُحذف هذا الملف كله — وهو مقياس التقدّم:
 * كلّما قصرت القائمة اقترب النظام القديم من الإطفاء.
 */
const LEGACY = process.env.LEGACY_ORIGIN ?? 'http://localhost:3000';

/** صفحات ما زال يخدمها الخادم القديم — تقصر القائمة كلّما تقدّم الترحيل */
const LEGACY_PAGES = [
  'logout', 'admin', 'track',
  'robots.txt', 'sitemap.xml', 'manifest.json', 'sw.js',
];
/* رُحّلت إلى Next: login · dashboard · onboarding — وملفّاتها القديمة باقية في
   public/ حتى تُحدَّث التوكيدات التي تحرسها في test/pages.mjs و
   test/pwa.mjs. القاعدة: لا يُحذف ملف قبل أن يُحدَّث حارسه، وإلا
   صار الفشل غامضاً بين «تصميم مكسور» و«اختبار متقادم».

   ★ وكل صفحة تخرج من هذه القائمة تدخل مطابقة `src/proxy.ts` في
   التعديل نفسه — لا قبله ولا بعده. الـproxy يعمل قبل إعادة الكتابة:
   لو طابق صفحةً ما زالت قديمة لحجب سكربتاتها، ولو تأخّر عن صفحةٍ
   رُحّلت لخُدمت بلا CSP. */

/**
 * ترويسات الأمان الأساسية — منقولة من `SECURITY_HEADERS` في
 * `server/http.js` بقيمها.
 *
 * ★ كان تطبيق Next لا يرسل أياً منها منذ بدأ الترحيل. أي أن كل
 * صفحة رُحّلت — الهبوط، الباقات، واجهات المتاجر بنماذج طلبها —
 * صارت قابلةً للتأطير داخل موقعٍ آخر (clickjacking) بلا أي عَرَض.
 *
 * وهي على **كل** المسارات لأنها لا تكلّف شيئاً: لا تمسّ التصيير
 * الساكن ولا سرعة التحميل. أمّا CSP فيحتاج nonce يُجبر التصيير عند
 * الطلب، فهو في `src/proxy.ts` على الصفحات الحسّاسة وحدها.
 *
 * والصفحات القديمة المُمرَّرة ترسل الترويسات نفسها بالقيم نفسها،
 * فالتكرار هناك لا يتعارض.
 */
const SECURITY_HEADERS = [
  { key: 'X-Content-Type-Options', value: 'nosniff' },
  { key: 'X-Frame-Options', value: 'SAMEORIGIN' },
  { key: 'Referrer-Policy', value: 'strict-origin-when-cross-origin' },
  { key: 'Permissions-Policy', value: 'geolocation=(), microphone=(), camera=(), payment=()' },
];

const nextConfig: NextConfig = {
  reactStrictMode: true,

  /* «X-Powered-By: Next.js» معلومةٌ مجّانية لمن يبحث عن ثغرات
     إصدارٍ بعينه — ولا يستفيد منها زائرٌ واحد */
  poweredByHeader: false,

  async headers() {
    return [{ source: '/:path*', headers: SECURITY_HEADERS }];
  },

  async rewrites() {
    return {
      // قبل ملفات Next: أصول ومسارات يملكها الخادم القديم دائماً
      beforeFiles: [
        { source: '/api/:path*', destination: `${LEGACY}/api/:path*` },
        { source: '/assets/:path*', destination: `${LEGACY}/assets/:path*` },
        { source: '/uploads/:path*', destination: `${LEGACY}/uploads/:path*` },

        /**
         * ★ صفحات المنصة التي لم تُرحَّل بعد.
         *
         * لا بدّ أن تُمرَّر **قبل** توجيه Next، وإلا التقطها مسار
         * `/[slug]` (واجهة المتجر) وأعاد ٤٠٤ لصفحة الدخول واللوحة.
         * وكلها في قائمة `RESERVED` في `src/slug.js`، فلا يمكن
         * لمتجر أن يحمل أياً منها ولا يقع تعارض.
         */
        ...LEGACY_PAGES.map((p) => ({
          source: `/${p}`,
          destination: `${LEGACY}/${p}`,
        })),
      ],
      afterFiles: [],
      /**
       * ★ شبكة الأمان: أي مسار لم يُرحَّل بعد يُخدَم من النظام
       * القديم بدل صفحة ٤٠٤. هذا ما يجعل الترحيل تدريجياً فعلاً
       * — الموقع كامل في كل لحظة، ولا ننتظر اكتمال كل الصفحات
       * قبل أن نرى أياً منها.
       */
      fallback: [
        { source: '/:path*', destination: `${LEGACY}/:path*` },
      ],
    };
  },

  // بعد الدمج صار القفل واحداً في الجذر نفسه، فلم يعد
  // Turbopack يحتاج تثبيتاً صريحاً — لكن التثبيت يبقى أرخص من
  // تخمينٍ يتغيّر لو أُضيف قفل آخر يوماً.
  turbopack: { root: __dirname },

  images: {
    // صور المنتجات تُرفع مضغوطة أصلاً من المتصفح؛ نكتفي بمقاسين
    deviceSizes: [640, 1080, 1920],
    imageSizes: [64, 120, 160, 320],

    /**
     * ★ AVIF ثم WebP — وهما الفارق الأكبر في هذا السوق تحديداً.
     *
     * أصول الصفحة PNG خام: `hero-laptop.png` وحدها ١٫٩ م.ب وتحمل
     * `priority` أي أنها صورة LCP. وبلا هذا السطر يخدم Next الصيغة
     * الأصلية كما هي. وAVIF يقصّها إلى عُشرها تقريباً على صورة
     * كهذه — والوثيقة نفسها (§٥٫٣) تقول إن «حجم الصور العامل
     * الأول» في سرعات السوق المستهدف.
     *
     * والترتيب مقصود: المتصفح يختار الأول الذي يدعمه، وAVIF أصغر.
     */
    formats: ['image/avif', 'image/webp'],
  },
};

export default nextConfig;
