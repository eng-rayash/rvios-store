/**
 * «أخرى» ليس قطاعاً يُسوَّق له — لا بطاقة له في صفحة القطاعات —
 * لكنه لازمٌ في المُنتقي وهو القيمة الافتراضية في قاعدة البيانات.
 * وضعُه خارج `SECTORS` يجعل الفرق بنيوياً لا اتفاقاً يُنسى.
 * @type {Sector}
 */
export const OTHER = {
  id: 'other', name: 'أخرى', img: 'other.webp',
  icon: 'M4 6h16M4 12h16M4 18h16',
  blurb: '', tags: [],
};

export const DEFAULT_SECTOR = OTHER.id;

/** ما يعرضه المُنتقي: القطاعات ثم «أخرى» في آخرها */
export const PICKABLE = [...SECTORS, OTHER];

/**
 * مُعرِّفات هُجرت ولا تزال في قاعدة البيانات.
 *
 * لا نُهاجر صفوف المتاجر: تاجر اختار «إكسسوارات» يوم كانت قطاعاً
 * قائماً لا يستحقّ أن يرى `accessories` خاماً فوق واجهته لأننا
 * أعدنا ترتيب قائمة. تُقرأ ولا تُقترح.
 */
export const LEGACY = {
  accessories: 'jewelry',
  sweets: 'food',
};

const BY_ID = new Map(PICKABLE.map((s) => [s.id, s]));

/** القطاع بمُعرِّفه بعد ردّ المهجور إلى خلفه، أو `null` */
export function sectorOf(id) {
  const key = LEGACY[id] ?? id;
  return BY_ID.get(key) ?? null;
}

/** الاسم المعروض، أو `''` لمُعرِّف لا نعرفه — فلا يُطبع خاماً */
export function labelOf(id) {
  return sectorOf(id)?.name ?? '';
}

/** هل هذا مُعرِّف نقبل حفظه؟ المهجور مقروء لا مقبول */
export function isSector(id) {
  return BY_ID.has(id);
}
