//  مولّد الأسرار
//
//  السبب في وجوده: كل سرّ يُكتب باليد يُختار ضعيفاً. تجربة
//  مكرّرة لا استثناء لها — «rvios2026» و«admin1234» وما شابه.
//  أمرٌ واحد يولّد ما لا يُخمَّن، فلا يبقى عذر.
//
//  التشغيل:  npm run secrets
// ═══════════════════════════════════════════════════════════
import crypto from 'node:crypto';

/** عشوائية من مصدر آمن، بترميز يسهل نسخه ولصقه */
const token = (bytes) => crypto.randomBytes(bytes).toString('base64url');

const SECRETS = [
  ['RVIOS_ADMIN_PASS', 24, 'كلمة مرور لوحة الإدارة — تحكم المنصة كلها'],
  ['OTP_PEPPER',       32, 'فلفل تجزئة رموز التحقق — تغييره يُبطل الرموز المعلّقة'],
  ['VISIT_SALT',       24, 'ملح بصمة الزيارة — ثابت كي لا تتضخّم أرقام الزوّار'],
  ['WA_VERIFY_TOKEN',  16, 'رمز تحقّق webhook واتساب — يُدخَل في لوحة Meta أيضاً'],
];

const lines = SECRETS.map(([key, bytes]) => `${key}=${token(bytes)}`);

console.log(`
  ═══ أسرار جديدة ═══

  انسخها إلى .env (أو إلى متغيّرات البيئة عند مزوّدك).
`);

for (const [key, , why] of SECRETS) {
  console.log(`  ${key}`);
  console.log(`    ${why}`);
}

console.log(`
  ───────────────────────────────────────────────────────────
${lines.map((l) => `  ${l}`).join('\n')}
  ───────────────────────────────────────────────────────────

  تنبيهان:

  • لا تُعِد توليد OTP_PEPPER على قاعدة عاملة — الرموز
    المرسَلة ولم تُستعمل بعد ستفشل كلها.

  • لا تلصق هذه القيم في محادثة أو تذكرة أو لقطة شاشة.
    ما يُنشر مرة يبقى منشوراً.
`);
